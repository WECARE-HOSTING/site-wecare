const ALL: Record<Lang, Messages> = { pt, en, es };

/** Everything a page or component needs to speak one language. */
export type T = Messages & {
  lang: Lang;
  locale: string;
  /** "3 noites", "1 night" … */
  n: (count: number, unit: [string, string]) => string;
  money: (value: number, currency?: string) => string;
  date: (isoDate: string, opts?: Intl.DateTimeFormatOptions) => string;
};

export function getMessages(lang: Lang): T {
  const locale = localeOf(lang);
  return {
    ...ALL[lang],
    lang,
    locale,
    n: (count, unit) => `${count} ${count === 1 ? unit[0] : unit[1]}`,
    money: (value, currency = "BRL") => new Intl.NumberFormat(locale, { style: "currency", currency, maximumFractionDigits: value % 1 === 0 ? 0 : 2 }).format(value),
    date: (iso, opts = { day: "numeric", month: "short" }) => new Intl.DateTimeFormat(locale, { ...opts, timeZone: "UTC" }).format(new Date(`${iso}T00:00:00Z`)),
  };
}
